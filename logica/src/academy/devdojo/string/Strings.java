package academy.devdojo.string;

public class Strings {
    public static void main(String[] args) {

        /* CHAR -  é alocado um espaço em memória de 8 bits. Este espaço alocado em memória é utilizado
        para armazenar somente 1 caracter. */

        // É possível informar um caracter de duas formas

        char letra = 'a';
        // ou
        char letraA = 65;

        // Bolean ( Possui 1 bit de informação ) só pode armazenar apenas 2 valores: 0 ou 1

        // Tipo para representar Verdadeiro / Falso

        Boolean botaoAtivado = true;
        System.out.println(botaoAtivado);

        Boolean botaoDesativado = false;
        System.out.println(botaoDesativado);

    }

}
